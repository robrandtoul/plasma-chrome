  (material_id, code, display_name, variant_type, ink_count, sort_order, is_active)
select
  m.id,
  v.code,
  v.display_name,
  'ink_count',
  v.ink_count,
  v.sort_order,
  true
from materials m
cross join (values
  ('5_ink', '5 Inks', 5, 50),
  ('6_ink', '6 Inks', 6, 60),
  ('7_ink', '7 Inks', 7, 70),
  ('8_ink', '8 Inks', 8, 80)
