-- Migration 000107: extend letterpress to 5 and 6 ink runs
--
-- Plasma is extending letterpress (plain and gilded) to support 5 and
-- 6 ink runs at standard published prices. The pricing rule, agreed
-- with Rob during recon, is a fixed delta:
--
--   p5 = p4 + (p4 - p3) = 2 * p4 - p3
--   p6 = p4 + 2 * (p4 - p3) = 3 * p4 - 2 * p3
--
-- The delta between 3_ink and 4_ink at a given (material, currency,
-- quantity) is applied again to extend the ladder. Spot-checked across
-- four anchors (q100, q500, q1000, q2000) in all three currencies for
-- both materials before generating: every delta is positive, every
-- ladder is monotonic, no inversions.
--
-- Gilded surcharge invariance: the gilded surcharge is per-quantity,
-- not per-ink-count, so it cancels out of the (p4 - p3) delta. This
-- means we can compute gilded p5 and p6 from gilded p3 and p4 directly
-- without referencing the plain table or the surcharge ladder.
-- Verified at the four anchors: gilded delta == plain delta in every
-- case across all three currencies.
--
-- Shape of this migration:
--
--   1. Insert four new material_variants rows for the gilded material
--      (5_ink, 6_ink, 7_ink, 8_ink). Plain letterpress already has
--      placeholder 5-8 ink variants from migration 000079 (added
--      cross-product to every ink_count material that existed at the
--      time); gilded was created in 000098 with only 1-4 ink and was
--      never back-filled. Adding 7_ink and 8_ink as zero-price
--      placeholders keeps gilded symmetric with plain: designers can
--      pick those variants and the form falls into custom-quote mode
--      (the same path taken by plain 7_ink/8_ink today).
--
--   2. Insert 924 price_tier rows: 77 quantities (100 to 2000 by 25)
--      x 2 ink counts (5_ink, 6_ink) x 3 currencies (GBP, EUR, USD)
--      x 2 materials (paper_letterpress, paper_letterpress_gilded).
--      Generated by scripts/generate_000107_tiers.py from the
--      canonical 3_ink and 4_ink rows already in the database. The
--      script reads seed.sql + migrations 000098, 000105, 000106 to
--      reconstruct the post-000106 state, then applies the delta
--      rule. Output pasted inline below.
--
-- Idempotency: both INSERTs use ON CONFLICT DO NOTHING. Re-applying
-- this migration is a no-op once the rows exist. Mirrors the 000079
-- and 000098 patterns.
--
-- Frontend impact: none. NewVersionPage variant loader filters only
-- on is_active, not on price-tier presence (see src/pages/
-- NewVersionPage.tsx:655-660), so 5_ink and 6_ink for gilded appear
-- in the picker as soon as the variant rows exist, and standard
-- pricing renders for 5/6 ink as soon as the price tiers exist.
-- 7_ink and 8_ink continue to fall into custom-quote mode for both
-- materials.
--
-- Display quantities and quote bounds are material-level (not
-- variant-level), so they are unchanged by this migration. The
-- existing settings already cover q100 to q2000.

