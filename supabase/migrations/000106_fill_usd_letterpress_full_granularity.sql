--
--    Path B (chosen by Rob during recon): overwrite the existing
--    q125-q200 gilded surcharges with the linear-interpolated values
--    derived from the published-chart anchors (q100=$60, q250=$120).
--    New surcharge ladder: $70, $80, $90, $100 (q125, q150, q175,
--    q200). The plain totals stay as is; only the gilded totals
--    shift down by $5-$20 per row.
--
--    Historical proofs are protected by the proof_versions
--    .pricing_snapshot model (snapshot taken at version creation;
--    customer page reads from snapshot for approved versions, not
--    from live price_tiers). Only newly-created proofs see the
--    smoothed values.
--
-- 2. INSERT 528 new rows for missing quantities (every q in 225,
--    275, 300, ..., 1975 by 25, excluding the 11 already in DB).
--    Linear interpolation between the seven published-chart
--    headline anchors (100, 250, 500, 750, 1000, 1500, 2000),
--    rounded to whole dollar. Same rule the GBP and EUR analysis
--    confirmed produces sub-£0.50/€0.50 deltas against actual
--    Plasma published prices. Gilded totals = plain interpolated
--    + interpolated surcharge.
--
--    Unit price = total / quantity to 4 decimal places, matching
--    the existing seed convention.
--
--    Four pre-existing plain rows have $1 rounding-direction
--    deltas vs the rule (q125/2ink, q200/2ink, q150/3ink,
--    q150/4ink). These are within the ±$0.50 rounding tolerance
--    seen across GBP and EUR; ON CONFLICT DO NOTHING preserves
--    the existing values.
--
-- After application:
--   paper_letterpress USD: 44 → 308 rows (4 ink × 77 quantities).
--   paper_letterpress_gilded USD: 44 → 308 rows.

