-- Migration 000098: split gilded letterpress and CNC carbon fibre into
-- distinct materials
--
-- Rationale: optional finishing that materially changes the product
-- (edge gilding on letterpress, CNC cutting on carbon fibre) is
-- promoted out of the per-material options / add-ons layer and
-- modelled as distinct materials. De-risks customer confusion on the
-- proof page and keeps the artwork the customer approves matching
-- the product they're ordering.
--
-- Shape of this migration:
--
--   1. Update base-material descriptions to drop references to the
--      optional finishing (now a separate product).
--   2. Insert two new materials: paper_letterpress_gilded and
--      carbon_fibre_cnc. Both carry display_quantities + quote
--      bounds + split-name surcharges mirroring their base
--      counterparts where applicable. Icons reuse the base URLs;
--      Plasma produces distinct icons later via the admin content
--      modal.
--   3. Insert material_variants: four ink_count variants (1-4 ink)
--      for gilded letterpress, one default variant for CNC carbon
--      fibre. Gilded letterpress matches the CSV coverage of 1-4
--      inks; base letterpress has 5-8 variants seeded but those
--      carry zero price tiers and aren't being replicated.
--   4. Insert ~753 price_tier rows for the new variants, generated
--      from the source CSVs by scripts/generate_000098_tiers.py
--      and pasted inline below.
--   5. Cleanup:
--      (a) Null the option_label on base carbon_fibre (was 'Cutting',
--          moot once the options are removed).
--      (b) Delete the two carbon_fibre material_options rows
--          (without_cutting and cnc_cutting). ON DELETE CASCADE on
--          material_option_surcharges drops the 117 surcharge rows
--          automatically.
--      (c) Delete the obsolete add_ons catalogue rows:
--          letterpress_gilding (never priced; replaced by the gilded
--          material) and carbon_cnc (same situation).
--
-- USD letterpress data gap: the source USD CSV carries only 5 tiers
-- (100 to 200 by 25), whereas GBP and EUR carry 77 tiers (100 to
-- 2000 by 25). The gilded USD tiers inherit this gap. Same
-- historical data limitation as seed.sql already flags for the
-- non-gilded USD letterpress.

