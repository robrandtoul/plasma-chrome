-- Migration 000108: extend letterpress to 7 and 8 ink runs
--
-- Continues the linear-extrapolation ladder established by migration
-- 000107 (5_ink and 6_ink). Same fixed delta rule, two more steps:
--
--   p7 = p4 + 3 * (p4 - p3) = 4 * p4 - 3 * p3
--   p8 = p4 + 4 * (p4 - p3) = 5 * p4 - 4 * p3
--
-- The delta between 3_ink and 4_ink at a given (material, currency,
-- quantity) is applied three more times to extend to 7_ink, four more
-- to 8_ink. Equivalently: p7 = p6 + delta, p8 = p7 + delta. Either
-- formulation gives the same numbers; the generator computes from
-- 3_ink and 4_ink directly, mirroring the 000107 generator.
--
-- Gilded surcharge invariance still holds. The gilded surcharge is
-- per-quantity, not per-ink-count, so it cancels out of the (p4 - p3)
-- delta. Gilded p7 and p8 are computed from gilded p3 and p4 directly,
-- without referencing the plain table.
--
-- Variant rows: no schema changes. Both materials already carry
-- 7_ink and 8_ink as placeholder variants. Plain letterpress got
-- them from 000079 (cross-product to every ink_count material at
-- the time). Gilded got them from 000107 (4-row insert that also
-- back-filled 5_ink and 6_ink variants). Until this migration runs,
-- 7_ink and 8_ink for both materials route through the form's
-- custom-quote path (zero price_tiers means custom quote). Once
-- this migration applies, standard pricing kicks in automatically;
-- no frontend changes needed.
--
-- Shape of this migration:
--
--   1. Insert 924 price_tier rows: 77 quantities (100 to 2000 by 25)
--      x 2 ink counts (7_ink, 8_ink) x 3 currencies (GBP, EUR, USD)
--      x 2 materials (paper_letterpress, paper_letterpress_gilded).
--      Generated by scripts/generate_000108_tiers.py from the
--      canonical 3_ink and 4_ink rows already in the database.
--      Output pasted inline below.
--
-- Idempotency: ON CONFLICT DO NOTHING on
-- (material_variant_id, currency, quantity). Re-applying this
-- migration is a no-op once the rows exist. Mirrors the 000107
-- pattern.
--
-- Verification noted during recon: ten £1 monotonicity dips in the
-- generated paper_letterpress 8_ink EUR ladder, all at the high end
-- (q1500 to q2000 in 25-unit steps). Cause: the underlying EUR plain
-- (p4 - p3) delta gently shrinks from 120 at q1500 down to 100 at
-- q2000, and the 8_ink rule multiplies that shrinking delta by four,
-- which amplifies tiny rounding artefacts in the source prices into
-- £1 reversals between consecutive quantities. Maximum magnitude:
-- £1 (0.08% of price; under £0.001 unit-price impact). The dips are
-- not present in any other bucket and not present in 7_ink anywhere.
-- Consistent with two pre-existing £1 dips in the live database
-- (paper_letterpress_gilded 3_ink and 4_ink USD, q200 to q225, also
-- artefacts of source-data interpolation in 000106). Accepted as a
-- faithful application of the rule rather than smoothed.

